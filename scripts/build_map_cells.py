#!/usr/bin/env python3
"""
One-time builder for js/map-cells.js: assigns each dot of the homepage night map
to a country, so the tool maps can light countries up.

Only needed if the map grid or country borders change. Not part of the monthly refresh.

Needs: pip install shapely
       Natural Earth 1:50m countries saved as scripts/ne_50m_admin_0_countries.geojson
       (github.com/nvkelso/natural-earth-vector, geojson folder; public domain)
Run from the repo root: python3 scripts/build_map_cells.py
"""
import collections, csv, json, os, re
from shapely.geometry import Point, shape
from shapely.strtree import STRtree

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COLS, ROWS, STEP, LAT_TOP = 160, 58, 2.25, 74
FIX = {"KOS": "XKX", "SOL": "SOM", "CYN": "CYP", "PSX": "PSE", "SAH": "ESH"}
MICRO = {"AND", "LIE", "SMR", "VAT", "MCO", "XKX"}   # too small for a dot at this scale
SMALL_PTS = {"TUV": (179.2, -8.5), "NRU": (166.9, -0.5), "MHL": (171.2, 7.1), "KIR": (173.0, 1.4),
             "PLW": (134.6, 7.5), "FSM": (158.2, 6.9), "MDV": (73.5, 4.2), "SGP": (103.8, 1.35),
             "BHR": (50.55, 26.0), "MLT": (14.4, 35.9), "SYC": (55.5, -4.6), "MUS": (57.55, -20.25)}

idx = open(os.path.join(ROOT, "index.html"), encoding="utf-8").read()
HEX = re.search(r'var HEX = "([0-9a-f]+)"', idx).group(1)
land = []
for ch in HEX:
    n = int(ch, 16); land += [n >> 3 & 1, n >> 2 & 1, n >> 1 & 1, n & 1]
land = land[:COLS * ROWS]

known = {r["iso3"] for r in csv.DictReader(open(os.path.join(ROOT, "scripts", "country-crosswalk.csv"), encoding="utf-8"))}
pp = open(os.path.join(ROOT, "js", "passport-data.js"), encoding="utf-8").read()
passport = set(json.loads(re.search(r"window\.CN_PASSPORT = (\{.*\});", pp, re.S).group(1))["codes"])

fc = json.load(open(os.path.join(ROOT, "scripts", "ne_50m_admin_0_countries.geojson"), encoding="utf-8"))
geoms, codes, rep = [], [], {}
for f in fc["features"]:
    p = f["properties"]
    a = p.get("ISO_A3_EH")
    if not a or a == "-99":
        a = p.get("ADM0_A3")
    a = FIX.get(p.get("ADM0_A3"), a)
    g = shape(f["geometry"])
    geoms.append(g); codes.append(a)
    rep.setdefault(a, g.representative_point())
tree = STRtree(geoms)

owner = {}
for i, b in enumerate(land):
    if not b:
        continue
    r, c = divmod(i, COLS)
    pt = Point(-180 + (c + .5) * STEP, LAT_TOP - (r + .5) * STEP)
    hit = [j for j in tree.query(pt) if geoms[j].contains(pt)]
    code = codes[hit[0]] if hit else codes[tree.nearest(pt)]
    owner[i] = code if code in known else None

# Give small sovereign states a dot: an empty cell where possible, else borrow one
# from a neighbor that has more than four.
cnt = collections.Counter(owner.values())
for iso in sorted(passport - set(cnt) - MICRO):
    pt = rep.get(iso)
    x, y = (pt.x, pt.y) if pt is not None else SMALL_PTS[iso]
    c, r = int((x + 180) // STEP), int((LAT_TOP - y) // STEP)
    cell = r * COLS + c
    if cell not in owner:
        owner[cell] = iso
    elif cnt[owner[cell]] > 4:
        cnt[owner[cell]] -= 1; owner[cell] = iso
    else:
        for n in [(r + dr) * COLS + (c + dc) for dr in (-1, 0, 1) for dc in (-1, 0, 1)]:
            if n not in owner:
                owner[n] = iso; break

isos = sorted({v for v in owner.values() if v})
flat = []
for cell in sorted(owner):
    if owner[cell]:
        flat += [cell, isos.index(owner[cell])]
out = {"cols": COLS, "rows": ROWS, "step": STEP, "latTop": LAT_TOP, "iso": isos, "dots": flat}
hdr = ("/* GENERATED by scripts/build_map_cells.py. Dots for the tool maps, on the same grid as the\n"
       "   homepage night map: 160 x 58 cells of 2.25 degrees, 74N to 56.5S.\n"
       "   dots: flat list of [cell, country] pairs. cell = row * 160 + col.\n"
       "   country indexes into iso (ISO 3166 alpha-3). Microstates and Kosovo are too small for a\n"
       "   dot at this scale; the tool tables still list them. */\n")
with open(os.path.join(ROOT, "js", "map-cells.js"), "w", encoding="utf-8") as f:
    f.write(hdr + "window.CN_MAPCELLS = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("Wrote js/map-cells.js: %d dots, %d countries" % (len(flat) // 2, len(isos)))
